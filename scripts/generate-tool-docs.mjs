/**
 * Generate docs/tools.md from the MCP tool registry so the catalog never drifts from the server.
 * Run after a build: `npm run docs:tools`.
 */
import { writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const repositoryRoot = resolve(fileURLToPath(new URL('..', import.meta.url)));
const registrars = await import(pathToFileURL(join(repositoryRoot, 'dist/mcp/tools/index.js')).href);

/** Catalog sections in reading order: [registrar export, heading, intro]. */
const SECTIONS = [
    ['registerIdentityTools', 'Identity and organization', 'Start here to confirm access and discover environments.'],
    ['registerProfileTools', 'Project profile', 'Bind a workspace to a named credential profile.'],
    [
        'registerAppReadTools',
        'Applications — read',
        'CloudHub 2.0 deployment state, specs, settings and cross-environment comparison.',
    ],
    [
        'registerAppDeployTools',
        'Applications — deploy',
        'Publish and deploy artifacts. Existing apps only have their artifact reference changed unless you ask otherwise.',
    ],
    ['registerAppLifecycleTools', 'Applications — lifecycle', 'Restart, scale, stop, start, settings and deletion.'],
    ['registerLogTools', 'Logs', 'Raw application logs.'],
    [
        'registerAnalysisTools',
        'Log analysis',
        'Clustered errors with context, recurring patterns and health statistics.',
    ],
    [
        'registerMonitoringTools',
        'Monitoring',
        'Traffic, failures, latency, JVM and host metrics. See [Monitoring](monitoring.md) for how to read them.',
    ],
    ['registerExchangeTools', 'Exchange', 'Search assets, read specs and publish application JARs.'],
    ['registerApiManagerTools', 'API Manager', 'API instances, policies and alerts.'],
    [
        'registerDesignCenterTools',
        'Design Center',
        'Read projects and files; writes and Exchange publication go through single-use preview tokens.',
    ],
    ['registerGovernanceTools', 'API Governance', 'Governance plans and conformance for API assets.'],
    ['registerAuditTools', 'Audit log', 'Who changed what, and when.'],
    ['registerAnypointMQTools', 'Anypoint MQ', 'Queues, statistics, dead-letter inspection and publishing.'],
    ['registerObjectStoreTools', 'Object Store', 'Stores, keys and values.'],
];

function collect(registrar) {
    const tools = [];
    const server = {
        registerTool(name, definition) {
            tools.push({ name, ...definition });
        },
    };
    registrar(server, {});
    return tools;
}

const ABBREVIATION = /\b(e\.g|i\.e|etc|vs)$/i;

/** First sentence of a description, ignoring the full stops inside common abbreviations. */
function summary(description) {
    const text = description.replace(/\s+/g, ' ').trim();
    for (const match of text.matchAll(/[.!?](?= |$)/g)) {
        if (!ABBREVIATION.test(text.slice(0, match.index))) {
            return text.slice(0, match.index + 1).replace(/\|/g, '\\|');
        }
    }
    return text.replace(/\|/g, '\\|');
}

function inputs(schema = {}) {
    const names = Object.entries(schema).map(([name, field]) => (field.isOptional?.() ? `${name}?` : name));
    return names.length ? names.map((name) => `\`${name}\``).join(', ') : '—';
}

function access(annotations = {}, schema = {}) {
    if (annotations.readOnlyHint) return 'read';
    const kind = annotations.destructiveHint ? '⚠️ write' : 'write';
    if ('previewToken' in schema) return `${kind} · preview token`;
    if ('confirm' in schema) return `${kind} · confirm`;
    return `${kind} · immediate`;
}

const covered = new Set(SECTIONS.map(([name]) => name));
const unknown = Object.keys(registrars).filter((name) => name.startsWith('register') && !covered.has(name));
if (unknown.length) throw new Error(`Add catalog sections for: ${unknown.join(', ')}`);

const lines = [
    '# Tool catalog',
    '',
    '<!-- Generated by scripts/generate-tool-docs.mjs from the MCP tool registry. Do not edit by hand. -->',
    '',
    'Every tool the MCP server registers. **read** tools never change anything. **write** tools change platform state,',
    'and **⚠️ write** marks tools that can replace or remove it. The guard after the access level says how a write',
    'is applied: **confirm** returns a dry-run preview until called with `confirm: true`; **preview token** needs the',
    'single-use token returned by the matching `preview_*` tool; **immediate** acts on the first call, so confirm',
    'intent with the user first. Production environments add their own checks; see the [safety model](safety.md).',
    'A `?` marks an optional input.',
];

for (const [registrar, heading, intro] of SECTIONS) {
    const tools = collect(registrars[registrar]);
    lines.push('', `## ${heading}`, '', intro, '', '| Tool | Access | Inputs | Summary |', '| --- | --- | --- | --- |');
    for (const tool of tools) {
        lines.push(
            `| \`${tool.name}\` | ${access(tool.annotations, tool.inputSchema)} | ${inputs(tool.inputSchema)} | ${summary(tool.description)} |`,
        );
    }
}

writeFileSync(join(repositoryRoot, 'docs/tools.md'), `${lines.join('\n')}\n`);
console.log('docs/tools.md regenerated.');
